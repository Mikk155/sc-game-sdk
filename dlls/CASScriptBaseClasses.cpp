void CASScriptBaseClasses::OutputToConsole(edict_s *player)
{
	char buffer[CONSOLE_BUFFER_SIZE];

	for (unsigned int i = FIRST_ENTITY_HEADER; i < GetBaseClassesCount(); i++)
	{
		int length = snprintf(buffer, sizeof(buffer), "%s\n", m_ScriptBaseClasses[i].m_pszSource);

		if (length >= 0 && (unsigned int)length < sizeof(buffer))
			CLIENT_PRINTF(player, print_console, buffer);
	}
}
