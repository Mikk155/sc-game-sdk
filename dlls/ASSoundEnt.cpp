#include "extdll.h"
#include "util.h"
#include "cbase.h"
#include "soundent.h"
#include "ASSoundEnt.h"
#include "CASDocumentation.h"
#include <stddef.h>

extern CSoundEnt *pSoundEnt;

namespace
{
unsigned int maximumSounds = MAX_WORLD_SOUNDS;
int emptySoundList = SOUNDLIST_EMPTY;
int freeSoundList = SOUNDLISTTYPE_FREE;
int activeSoundList = SOUNDLISTTYPE_ACTIVE;
int neverExpire = SOUND_NEVER_EXPIRE;
}

CSoundEnt *GetSoundEntInstance( void )
{
	return pSoundEnt;
}

void CSoundEnt_InsertSound( int type, const Vector &origin, int volume, float duration,
                            CBaseEntity *owner, CSoundEnt * )
{
	CSoundEnt::InsertSound( type, origin, volume, duration, owner );
}

int CSoundEnt_ActiveList( CSoundEnt * )
{
	return CSoundEnt::ActiveList();
}

int CSoundEnt_FreeList( CSoundEnt * )
{
	return CSoundEnt::FreeList();
}

CSound *CSoundEnt_SoundPointerForIndex( int index, CSoundEnt * )
{
	return CSoundEnt::SoundPointerForIndex( index );
}

int CSoundEnt_ClientSoundIndex( edict_t *client, CSoundEnt * )
{
	return CSoundEnt::ClientSoundIndex( client );
}

void RegisterSCScriptSoundEntClass( CASDocumentation *documentation )
{
	documentation->RegisterObjectType( "Sound class used by CSoundEnt", "CSound", 0, asOBJ_REF | asOBJ_NOCOUNT );
	documentation->RegisterObjectMethod( "Clears the sound",
	                                     "CSound", "void Clear()", asMETHOD( CSound, Clear ), asCALL_THISCALL );
	documentation->RegisterObjectMethod( "Resets the sound",
	                                     "CSound", "void Reset()", asMETHOD( CSound, Reset ), asCALL_THISCALL );
	documentation->RegisterObjectProperty( "Sound's location in space",
	                                       "CSound", "Vector m_vecOrigin", offsetof( CSound, m_vecOrigin ) );
	documentation->RegisterObjectProperty( "What type of sound this is",
	                                       "CSound", "int m_iType", offsetof( CSound, m_iType ) );
	documentation->RegisterObjectProperty( "How loud the sound is",
	                                       "CSound", "int m_iVolume", offsetof( CSound, m_iVolume ) );
	documentation->RegisterObjectProperty( "When the sound should be purged from the list",
	                                       "CSound", "float m_flExpireTime", offsetof( CSound, m_flExpireTime ) );
	documentation->RegisterObjectProperty( "Index of next sound in this list ( Active or Free )",
	                                       "CSound", "int m_iNext", offsetof( CSound, m_iNext ) );
	documentation->RegisterObjectProperty( "Temporary link that monsters use to build a list of audible sounds",
	                                       "CSound", "int m_iNextAudible", offsetof( CSound, m_iNextAudible ) );
	documentation->RegisterObjectProperty( "Sounds now have OWNERS... (For various AI checks)",
	                                       "CSound", "EHandle hOwner", offsetof( CSound, m_hOwner ) );
	documentation->RegisterObjectMethod( "Returns whether this is a sound",
	                                     "CSound", "bool FIsSound()", asMETHOD( CSound, FIsSound ), asCALL_THISCALL );
	documentation->RegisterObjectMethod( "Returns whether this is a scent",
	                                     "CSound", "bool FIsScent()", asMETHOD( CSound, FIsScent ), asCALL_THISCALL );
}

void RegisterSCScriptSoundEnt( CASDocumentation *documentation )
{
	documentation->RegisterGlobalProperty( "maximum number of sounds handled by the world at one time.\nSee CSoundEnt.", "const size_t MAX_WORLD_SOUNDS", &maximumSounds );
	documentation->RegisterEnum( "Sound flags for monster schedules.", "bits_SOUND" );
	documentation->RegisterEnumValue( "", "bits_SOUND", "bits_SOUND_NONE", 0 );
	documentation->RegisterEnumValue( "gunshots, explosions", "bits_SOUND", "bits_SOUND_COMBAT", 1 );
	documentation->RegisterEnumValue( "door opening/closing, glass breaking", "bits_SOUND", "bits_SOUND_WORLD", 2 );
	documentation->RegisterEnumValue( "all noises generated by player. walking, shooting, falling, splashing", "bits_SOUND", "bits_SOUND_PLAYER", 4 );
	documentation->RegisterEnumValue( "dead body", "bits_SOUND", "bits_SOUND_CARCASS", 8 );
	documentation->RegisterEnumValue( "gib or pork chop", "bits_SOUND", "bits_SOUND_MEAT", 16 );
	documentation->RegisterEnumValue( "pending danger. Grenade that is about to explode, explosive barrel that is damaged, falling crate", "bits_SOUND", "bits_SOUND_DANGER", 32 );
	documentation->RegisterEnumValue( "trash cans, banana peels, old fast food bags.", "bits_SOUND", "bits_SOUND_GARBAGE", 64 );
	documentation->RegisterEnumValue( "a bullet just hit at this location", "bits_SOUND", "bits_SOUND_BULLETHIT", 128 );
	documentation->RegisterEnumValue( "All sound flags", "bits_SOUND", "bits_ALL_SOUNDS", -1 );
	documentation->RegisterGlobalProperty( "Indicates that the sound list is empty.\nSee CSoundEnt.", "const int SOUNDLIST_EMPTY", &emptySoundList );
	documentation->RegisterGlobalProperty( "Identifiers passed to functions that can operate on either list, to indicate which list to operate on.\nSee CSoundEnt.", "const int SOUNDLISTTYPE_FREE", &freeSoundList );
	documentation->RegisterGlobalProperty( "Identifiers passed to functions that can operate on either list, to indicate which list to operate on.\nSee CSoundEnt.", "const int SOUNDLISTTYPE_ACTIVE", &activeSoundList );
	documentation->RegisterGlobalProperty( "With this set as a sound's ExpireTime, the sound will never expire.\nSee CSoundEnt.", "const int SOUND_NEVER_EXPIRE", &neverExpire );

	RegisterSCScriptSoundEntClass( documentation );

	documentation->RegisterObjectType( "Sound manager entity. Manages sound events made in the world, like gunfire.\nDoes not handle the playing of sounds, see CSoundEngine for actual sound playing.", "CSoundEnt", sizeof( CSoundEnt ), asOBJ_REF | asOBJ_NOCOUNT );
	documentation->RegisterObjectMethod( "Inserts a sound. iType is one of the bits_SOUND enum.",
	                                     "CSoundEnt", "void InsertSound(int iType, const Vector& in vecOrigin, int iVolume, float flDuration, CBaseEntity@ pOwner)", asFUNCTION( CSoundEnt_InsertSound ), asCALL_CDECL_OBJLAST );
	documentation->RegisterObjectMethod( "Returns the head of the active list.",
	                                     "CSoundEnt", "int ActiveList()", asFUNCTION( CSoundEnt_ActiveList ), asCALL_CDECL_OBJLAST );
	documentation->RegisterObjectMethod( "Returns the head of the free list.",
	                                     "CSoundEnt", "int FreeList()", asFUNCTION( CSoundEnt_FreeList ), asCALL_CDECL_OBJLAST );
	documentation->RegisterObjectMethod( "Return a pointer for this index in the sound list.\nIndex must be between 0 and MAX_WORLD_SOUNDS.",
	                                     "CSoundEnt", "CSound@ SoundPointerForIndex(int iIndex)", asFUNCTION( CSoundEnt_SoundPointerForIndex ), asCALL_CDECL_OBJLAST );
	documentation->RegisterObjectMethod( "Gets the index for the given client.",
	                                     "CSoundEnt", "int ClientSoundIndex(edict_t@ pClient)", asFUNCTION( CSoundEnt_ClientSoundIndex ), asCALL_CDECL_OBJLAST );
	documentation->RegisterObjectMethod( "Returns whether the sound list is empty.",
	                                     "CSoundEnt", "bool IsEmpty()", asMETHOD( CSoundEnt, IsEmpty ), asCALL_THISCALL );
	documentation->RegisterObjectMethod( "Returns the number of sounds in the given list. Must be either SOUNDLISTTYPE_FREE or SOUNDLISTTYPE_ACTIVE.",
	                                     "CSoundEnt", "int ISoundsInList(int iListType)", asMETHOD( CSoundEnt, ISoundsInList ), asCALL_THISCALL );
	documentation->RegisterObjectProperty( "keeps track of the number of active sounds at the last update. (for diagnostic work)",
	                                       "CSoundEnt", "const int m_cLastActiveSounds", offsetof( CSoundEnt, m_cLastActiveSounds ) );
	documentation->RegisterGlobalFunction( "Gets the current global sound manager entity",
	                                       "CSoundEnt@ GetSoundEntInstance()", asFUNCTION( GetSoundEntInstance ), asCALL_CDECL );
}
