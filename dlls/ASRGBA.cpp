void RegisterSCScriptRGBA(CASDocumentation *documentation)
{
	documentation->RegisterObjectType("Color stored as four uint8 components", "RGBA", sizeof(RGBA), asOBJ_VALUE);
	documentation->RegisterObjectBehaviour("Constructor", "RGBA", asBEHAVE_CONSTRUCT,
		"void RGBA()", asFUNCTION(ConstructRGBA), asCALL_CDECL_OBJLAST);
	documentation->RegisterObjectBehaviour("Constructor", "RGBA", asBEHAVE_CONSTRUCT,
		"void RGBA(uint8 r, uint8 g, uint8 b, uint8 a = 255)",
		asFUNCTION(ConstructRGBAComp), asCALL_CDECL_OBJLAST);
	documentation->RegisterObjectBehaviour("Constructor", "RGBA", asBEHAVE_CONSTRUCT,
		"void RGBA(const Vector& in color, uint8 a = 255)",
		asFUNCTION(ConstructRGBAFromVector), asCALL_CDECL_OBJLAST);
	documentation->RegisterObjectBehaviour("Copy constructor", "RGBA", asBEHAVE_CONSTRUCT,
		"void RGBA(const RGBA& in other)", asFUNCTION(CopyConstructRGBA), asCALL_CDECL_OBJLAST);
	documentation->RegisterObjectBehaviour("Destructor", "RGBA", asBEHAVE_DESTRUCT,
		"void RGBA()", asFUNCTION(DestructRGBA), asCALL_CDECL_OBJLAST);
	documentation->RegisterObjectMethod("Assignment operator", "RGBA", "RGBA& opAssign(const RGBA& in other)",
		asFUNCTION(AssignRGBA), asCALL_CDECL_OBJLAST);
	documentation->RegisterObjectMethod("Compare colors", "RGBA", "bool opEquals(const RGBA& in other) const",
		asFUNCTION(RGBA_Equals), asCALL_CDECL_OBJLAST);
	documentation->RegisterObjectProperty("Red component", "RGBA", "uint8 r", asOFFSET(RGBA, r));
	documentation->RegisterObjectProperty("Green component", "RGBA", "uint8 g", asOFFSET(RGBA, g));
	documentation->RegisterObjectProperty("Blue component", "RGBA", "uint8 b", asOFFSET(RGBA, b));
	documentation->RegisterObjectProperty("Alpha component", "RGBA", "uint8 a", asOFFSET(RGBA, a));
	documentation->RegisterObjectMethod("Returns a string representation of this RGBA", "RGBA",
		"string ToString(const bool withAlpha = true) const", asFUNCTION(RGBA_ToString), asCALL_CDECL_OBJLAST);
}

